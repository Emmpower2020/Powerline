--  بعد از این مهاجرت + آپلود پوشهٔ Powerline (بک‌اند 4.3.85):
--   * در فرم ثبت/ویرایش/کپی کاربر، فیلد «امور بهره‌برداری» چندتایی می‌شود
--     (چک‌باکس + جستجو + بج) — می‌توانید چند امور برای یک نفر انتخاب کنید
--   * کاربر داده‌های «همهٔ امورهای انتخاب‌شده» را می‌بیند — مثلاً:
--     کارشناس انبارِ مشترک دو امور، مدیر پیمانکار با همهٔ امورهای خودش
--   * بدون انتخاب هیچ اموری = مدیر سیستم (دسترسی کامل به همهٔ امور)
--     — مثل قبل: من مدیر و مدیرعامل همهٔ امورها را می‌بینیم
--   * ایمپورت اکسل کاربران: ستون «امور بهره‌برداری» می‌تواند چندتایی باشد
--     (با «،» جدا کنید — مثلاً: کرمانشاه غربی، ایلام)
--
--  سازگاری:
--   * کاربران قبلی که یک امور داشتند، بدون تغییر کار می‌کنند — مقدار
--     district_ids آن‌ها به‌صورت خودکار از همان district_id قدیمی ساخته می‌شود
--     (نیازی به UPDATE دستی نیست؛ برنامه خودش fallback می‌کند)
--   * کاربرانی که امور نداشتند (مدیر سیستم) مثل قبل دسترسی کامل می‌مانند
--   * این اسکریپت «تکرار-امن» است؛ اجرای دوباره داده‌ای را خراب نمی‌کند
--     (به‌جز خطای «ستون تکراری» در بخش ۱ که قابل نادیده‌گرفتن است).
--   * کاربران بعد از تغییر امورهایشان یک‌بار «خروج و ورود» کنند تا لیست
--     امورهای جدید در نشستشان اعمال شود.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- بخش ۱ — ستون جدید جدول users
--  district_ids: لیست JSON شناسهٔ امورهای قابل‌مشاهدهٔ کاربر
--    [3,7]  → کاربر فقط داده‌های امور ۳ و ۷ را می‌بیند
--    NULL   → سازگار با قبل: همان district_id تک‌امور قدیمی ملاک است
--    []     → همهٔ امور (مدیر سیستم) — برنامه این حالت را با NULL district_id
--             همیشه همگام نگه می‌دارد
--  (اگر خطای Duplicate column داد یعنی قبلاً اجرا شده — نادیده بگیرید)
-- ----------------------------------------------------------------------------
ALTER TABLE `users`
  ADD COLUMN `district_ids` TEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL AFTER `district_id`;

